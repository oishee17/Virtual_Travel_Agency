# Read current file
with open('translations.js', 'r', encoding='utf-8') as f:
    content = f.read()

# Remove closing of translations object
content = content.rstrip()
if content.endswith('};'):
    content = content[:-2].rstrip()

# Add foreign languages
lang_entries = []
for code, data in foreign_langs.items():
    lines = [f'    {code}: {{']
    keys = list(data.keys())
    for i, key in enumerate(keys):
        val = data[key].replace('"', '\\"')
        comma = ',' if i < len(keys) - 1 else ''
        lines.append(f'        {key}: "{val}"{comma}')
    lines.append('    },')
    lang_entries.append('\n'.join(lines))

content += '\n' + '\n\n'.join(lang_entries) + '\n};\n'

with open('translations.js', 'w', encoding='utf-8') as f:
    f.write(content)

print(f"Added {len(foreign_langs)} foreign language translations")
print(f"Languages: {', '.join(foreign_langs.keys())}")
